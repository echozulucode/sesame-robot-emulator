#!/usr/bin/env node
/**
 * Project `hardware/source-annotations.json` into a typed module the app can
 * import, exactly the way `build-architecture-graph.mjs` projects
 * `hardware/hardware-map.json`.
 *
 * Why a generator rather than a JSON import: the same reason the architecture
 * graph has one. `--check` runs in `pnpm --filter @sesame-lab/web test`, so the
 * app cannot drift from the artefact, and the emitted module carries `readonly`
 * types that a raw JSON import would widen to `string`.
 *
 * Nothing is invented here. The only things this file adds to L3's data are:
 *
 *  - `SOURCE_FILES`, lifted out of `meta.filesAnnotated[]`, because the
 *    integrity gate in the browser needs the line count and the sha256 in one
 *    place; and
 *  - the four file paths as a union type, so a typo in a file name is a
 *    compile error rather than a 404 at runtime.
 *
 * The joins (node <-> symbol, joint <-> symbol, trace row <-> symbol) are NOT
 * precomputed here. They are line containment, they are cheap, and computing
 * them at runtime means they can never disagree with the data actually loaded.
 *
 * Regenerate: node apps/web/scripts/build-source-annotations-module.mjs
 * Check:      node apps/web/scripts/build-source-annotations-module.mjs --check
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, '..');
const REPO = path.resolve(APP, '../..');
const SOURCE = path.join(REPO, 'hardware/source-annotations.json');
const OUT = path.join(APP, 'src/generated/source-annotations.ts');
const CHECK = process.argv.includes('--check');

const annotations = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

// The pin has to agree with the graph's, or a symbol range and a node's
// `sourceRef` would be line numbers into two different trees while looking
// identical. Read the graph's constant rather than re-deriving it.
const graphText = fs.readFileSync(path.join(APP, 'src/generated/architecture-graph.ts'), 'utf8');
const graphCommit = /export const UPSTREAM_COMMIT = "([0-9a-f]{40})"/.exec(graphText)?.[1] ?? null;
if (graphCommit !== annotations.meta.upstreamCommit) {
  console.error(
    `FAIL  source-annotations.json pins ${annotations.meta.upstreamCommit} but ` +
      `architecture-graph.ts pins ${graphCommit}. A symbol range and a node sourceRef would be ` +
      `line numbers into two different trees.`,
  );
  process.exit(1);
}

for (const file of annotations.meta.filesAnnotated) {
  if (!/^[0-9a-f]{64}$/.test(file.sha256)) {
    console.error(`FAIL  ${file.file} has no usable sha256 — the browser integrity gate needs one`);
    process.exit(1);
  }
}

const j = (value) => JSON.stringify(value);
const rows = (list) => list.map((item) => `  ${j(item)},`).join('\n');

const files = annotations.meta.filesAnnotated;
const fileUnion = files.map((f) => j(f.file)).join(' | ');
const KINDS = [
  'entrypoint',
  'handler',
  'helper',
  'pose-function',
  'movement-function',
  'region',
  'type',
  'table',
  'macro',
  'config',
  'state',
  'data',
];

const out = `/**
 * GENERATED by apps/web/scripts/build-source-annotations-module.mjs — do not edit.
 *
 * Projected verbatim from \`hardware/source-annotations.json\` (L3), which
 * resolves every line number against upstream
 * \`${annotations.meta.upstreamCommit}\`.
 *
 * ${annotations.symbols.length} symbols · ${annotations.concepts.length} concepts · ${annotations.teachingNotes.length} teaching notes · ${annotations.curriculum.length} curriculum modules.
 *
 * The source TEXT is not in here. It lives in the gitignored
 * \`firmware/upstream/\`, is served at \`upstream/<file>\` by the Vite plugin in
 * \`vite.config.ts\`, and is verified in the browser against
 * {@link SOURCE_FILES}'s \`sha256\` before a single line is rendered.
 *
 * Regenerate: node apps/web/scripts/build-source-annotations-module.mjs
 * Check:      node apps/web/scripts/build-source-annotations-module.mjs --check
 */

/** The four annotated files. A typo is a compile error, not a 404. */
export type SourceFileName = ${fileUnion};

/**
 * One annotated file: how long it is, and what it must hash to.
 *
 * \`sha256\` is the whole point of this export. \`firmware/upstream/\` is fetched
 * by script and gitignored, so the bytes the browser receives are not
 * guaranteed to be the bytes L3 measured — and source rendered at the wrong
 * line numbers is worse than no source at all.
 */
export interface SourceFileFacts {
  readonly file: SourceFileName;
  readonly lines: number;
  readonly sha256: string;
}

export const SOURCE_FILES: readonly SourceFileFacts[] = [
${rows(files.map((f) => ({ file: f.file, lines: f.lines, sha256: f.sha256 })))}
];

/** The commit every line number in this module points into. */
export const ANNOTATIONS_UPSTREAM_COMMIT = ${j(annotations.meta.upstreamCommit)} as const;

/** L3's own statement of what may and may not be claimed. Rendered in the UI. */
export const NO_HARDWARE_CLAIMS = ${j(annotations.meta.noHardwareClaims)};

export type SymbolKind =
${KINDS.map((k) => `  | ${j(k)}`).join('\n')}
;

/** Entity keys into \`hardware/hardware-map.json\`, resolved by L3's validator. */
export interface SymbolCrossRefs {
  readonly movements?: readonly string[];
  readonly commands?: readonly string[];
  readonly routes?: readonly string[];
  readonly bootSteps?: readonly number[];
  readonly faces?: readonly string[];
  readonly serialCli?: readonly string[];
  /** The call graph — "what ran next?". */
  readonly calls?: readonly string[];
  readonly hardwareMap?: readonly string[];
}

export interface SourceSymbol {
  readonly id: string;
  readonly kind: SymbolKind;
  readonly file: SourceFileName;
  /** 1-based, inclusive, into the pinned tree. */
  readonly startLine: number;
  readonly endLine: number;
  readonly lineCount: number;
  /** The exact text of \`startLine\`. The UI asserts this before rendering. */
  readonly startLineText: string;
  readonly endLineText: string;
  readonly signature: string;
  /** What the code DOES. Checkable against the cited lines. */
  readonly description: string;
  readonly concepts: readonly string[];
  /** Joints this span commands directly, in firmware enum order. Never re-sort. */
  readonly robotParts: readonly string[];
  /** Including joints reached through calls. Movements only. */
  readonly robotPartsTransitive?: readonly string[];
  readonly crossRefs: SymbolCrossRefs;
  readonly teachingNotes: readonly string[];
  readonly lesson: string | null;
  readonly lessons: readonly string[];
  /** A JUDGEMENT, not a fact. Must not render like \`description\`. */
  readonly commentary: string | null;
}

export const SOURCE_SYMBOLS: readonly SourceSymbol[] = [
${rows(annotations.symbols)}
];

/** The three explanatory levels the research report asks for. */
export interface ConceptLevels {
  readonly beginner12: string;
  readonly beginnerProgrammer: string;
  readonly architecture: string;
}

export interface SourceCitation {
  readonly file: SourceFileName;
  readonly line: number;
  readonly text: string;
}

export interface SourceConcept {
  readonly id: string;
  readonly label: string;
  /** Copied word for word from the research report's table. */
  readonly verbatimFromReport: boolean;
  readonly levels: ConceptLevels;
  readonly primaryAnchor: (SourceCitation & { readonly symbol: string }) | null;
  /** DENSE: \`face\` 38, \`timing\` 33, \`animation\` 33. Weight or cap it. */
  readonly symbols: readonly string[];
  readonly teachingNotes: readonly string[];
  readonly lessons: readonly string[];
}

export const SOURCE_CONCEPTS: readonly SourceConcept[] = [
${rows(annotations.concepts)}
];

/**
 * Evidence that lives in a LIBRARY, not in the pinned tree.
 *
 * Deliberately not shaped like a firmware citation: there is no repo path that
 * survives a clean clone, so the citable identity is library + version +
 * path-within-library + line. The UI must render it differently for the same
 * reason — it cannot be checked against the tree the rest of the pane shows.
 */
export interface LibraryEvidence {
  readonly library: string;
  readonly version: string;
  readonly file: string;
  readonly line: number;
  readonly text: string;
}

export interface TeachingNote {
  readonly id: string;
  readonly title: string;
  readonly kind: 'defect' | 'surprise' | 'design';
  readonly severity: 'high' | 'medium' | 'low' | 'info';
  readonly summary: string;
  readonly evidence: readonly SourceCitation[];
  readonly libraryEvidence: LibraryEvidence | null;
  readonly symbols: readonly string[];
  readonly concepts: readonly string[];
  readonly references: readonly string[];
  /** A judgement. Rendered apart from \`summary\`. */
  readonly commentary: string | null;
}

export const TEACHING_NOTES: readonly TeachingNote[] = [
${rows(annotations.teachingNotes)}
];

export interface CurriculumModule {
  readonly id: string;
  readonly module: string;
  readonly mainExperience: string;
  readonly realSesameConcept: string;
  readonly concepts: readonly string[];
  readonly symbols: readonly string[];
  readonly teachingNotes: readonly string[];
  /**
   * \`factual\` — at least one backing symbol, validated.
   * \`conceptual\` — NO backing symbol exists. The UI must say so and must not
   * frame the module as "this is how Sesame actually works".
   */
  readonly grounding: 'factual' | 'conceptual';
  /** A real boundary that does not disqualify a \`factual\` module. */
  readonly groundingNote: string | null;
  /** Required when \`grounding === 'conceptual'\`. */
  readonly conceptualReason: string | null;
}

export const CURRICULUM: readonly CurriculumModule[] = [
${rows(annotations.curriculum)}
];
`;

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error(
      'FAIL  src/generated/source-annotations.ts is stale.\n' +
        '      Regenerate: node apps/web/scripts/build-source-annotations-module.mjs',
    );
    process.exit(1);
  }
  console.log(
    `OK    source-annotations module current — ${annotations.symbols.length} symbols, ` +
      `${annotations.concepts.length} concepts, ${annotations.teachingNotes.length} notes, ` +
      `${annotations.curriculum.length} modules @ ${annotations.meta.upstreamCommit.slice(0, 7)}`,
  );
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(REPO, OUT)} (${annotations.symbols.length} symbols)`);
